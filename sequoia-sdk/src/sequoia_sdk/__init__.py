"""IV&V Python SDK — a Pythonic gRPC client for the Acadia ``HalService``.

Public API:

* :func:`connect` — open a :class:`Device` connection.
* :class:`Device` — discovery and lifecycle.
* :class:`Peripheral` — one HAL module's test surface.
* Exception hierarchy rooted in :class:`IVVError`.

Example:
    >>> import sequoia_sdk as ivv
    >>> with ivv.connect("192.168.1.50:50051") as dev:
    ...     imu = dev.peripheral("imu")
    ...     result = imu.run_oneshot()
    ...     print(result.output.metrics["accel_x"].double_value)
"""
from __future__ import annotations

from sequoia_sdk._version import __contracts_version__, __version__

try:
    from sequoia_sdk._convert import metric_value
    from sequoia_sdk.client import Device, connect
    from sequoia_sdk.exceptions import (
        ConfigError,
        ConnectionError,
        IVVError,
        NotSupported,
        PeripheralNotFound,
        TestError,
        TimeoutError,
    )
    from sequoia_sdk.peripheral import LongRunningSession, Peripheral
except ModuleNotFoundError as _e:
    # Tolerate the bootstrap window where `sequoia_sdk.types` / `sequoia_sdk._proto`
    # have not yet been generated by tools/gen_types.py — codegen needs to
    # import this package to run. Any *other* missing module is a real bug.
    if _e.name not in {"sequoia_sdk.types", "sequoia_sdk._proto",
                       "sequoia_sdk.types.common", "sequoia_sdk.types.hal_service"}:
        raise

__all__ = [
    "ConfigError",
    "ConnectionError",
    "Device",
    "IVVError",
    "LongRunningSession",
    "NotSupported",
    "Peripheral",
    "PeripheralNotFound",
    "TestError",
    "TimeoutError",
    "__contracts_version__",
    "__version__",
    "connect",
    "metric_value",
]
